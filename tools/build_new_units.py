def grade(parts: dict, colors: dict, g: int) -> tuple[dict, dict]:
    """대표 모습 → g 등급 모습: 망토(1+), 무기 강화, 티아라(4), 왕관(5), 등급 색"""
    p, c = dict(parts), dict(colors)
    if 'アイテム1' in p:
        p['アイテム1'] = item_at(p['アイテム1'], g)
    if g >= 1:
        p['マント類1'] = f'マント00{min(4, g)}'
        c['マント類1'] = GRADE_TINT[g]
    has_hat = '帽子類1' in p
    if g == 4:
        p['帽子類2' if has_hat else '帽子類1'] = '帽子003_ティアラ'
    if g == 5:
        p['帽子類2' if has_hat and p['帽子類1'] != '帽子002_王冠' else '帽子類1'] = '帽子002_王冠'
        c['衣装1'] = c.get('衣装1', C(1, 1, 1)).replace('Tint(', 'Tint(').strip()
    return p, c


def check(parts: dict) -> list[str]:
    """없는 파츠 이름 목록"""
    folders: dict[str, list[str]] = {}
    for name, folder, _ in LAYERS:
        folders.setdefault(name, []).append(folder)
    missing = []
    for layer, file in parts.items():
        if not any((PARTS / f / f'{file}.png').exists() for f in folders.get(layer, [])):
            missing.append(f'{layer}={file}')
    return missing


if __name__ == '__main__':
    bad = []
    for sheet, parts, colors in UNITS:
        for g in range(6):
            p, c = grade(parts, colors, g)
            miss = check(p)
            if miss:
                bad.append(f'{sheet}_{g}: {miss}')
                continue
            compose(p, c).save(OUT / f'{sheet}_{g}.png')
    if bad:
        print('\n'.join(bad))
        sys.exit(1)
    print('ok', len(UNITS) * 6)
